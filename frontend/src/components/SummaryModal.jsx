import { useEffect, useState } from "react";
import { Loader2, X } from "lucide-react";
import { api, errorMessage } from "../services/api";

export default function SummaryModal({ doc, onClose }) {
  const [data, setData] = useState(doc.summary || null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);

  async function generate() {
    setLoading(true); setError("");
    try { setData(await api.summarize(doc.id)); } catch (e) { setError(errorMessage(e)); }
    setLoading(false);
  }
  useEffect(() => { if (!doc.summary) generate(); /* eslint-disable-next-line */ }, []);

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/40 p-4">
      <div className="card max-h-[85vh] w-full max-w-2xl overflow-y-auto">
        <div className="mb-3 flex items-start justify-between">
          <h2 className="font-semibold">Summary: {doc.filename}</h2>
          <button onClick={onClose} aria-label="Close"><X size={18} /></button>
        </div>
        {loading && <p className="flex items-center gap-2 text-sm"><Loader2 className="animate-spin" size={16} /> Generating…</p>}
        {error && <p className="text-sm text-red-600">{error}</p>}
        {data && (
          <div className="space-y-4 text-sm">
            <p className="text-xs text-slate-500">
              {data.mode === "llm" ? "Generated by the configured LLM." : "Extractive summary: sentences selected from the document (not AI-generated text)."}
            </p>
            <section><h3 className="mb-1 font-medium">Concise summary</h3><p>{data.summary}</p></section>
            <section><h3 className="mb-1 font-medium">Key points</h3>
              <ul className="list-disc space-y-1 pl-5">{data.key_points.map((k) => <li key={k}>{k}</li>)}</ul></section>
            <section><h3 className="mb-1 font-medium">Important topics</h3>
              <div className="flex flex-wrap gap-2">{data.topics.map((t) => <span key={t} className="rounded-full bg-indigo-50 px-2 py-0.5 text-xs text-indigo-700 dark:bg-slate-700 dark:text-indigo-300">{t}</span>)}</div></section>
          </div>
        )}
        <div className="mt-4 flex justify-end gap-2">
          {data && <button className="btn-ghost" onClick={generate} disabled={loading}>Regenerate</button>}
          <button className="btn" onClick={onClose}>Close</button>
        </div>
      </div>
    </div>
  );
}
